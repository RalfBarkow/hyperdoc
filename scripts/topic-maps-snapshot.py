#!/usr/bin/env python3
"""Runtime snapshot of a pinned Topic Maps commit, for the hyperdoc-catalog-topic-maps package.

  create  REPO COMMIT OUTDIR       write the archive and HyperDoc's manifest; reads REPO only
  verify  REPO COMMIT ARCHIVE MANIFEST EVIDENCE.json
                                   check, with Git and Nix and independently of the Lisp verifier, that the
                                   archive is exactly the commit's tree without the excluded entries

The snapshot is `git archive` of every root entry except EXCLUDED. Nothing is edited, generated or normalised.
"""
import gzip, hashlib, io, json, os, subprocess, sys, tarfile, tempfile, time

EXCLUDED = ["reports"]
FORMAT = "hyperdoc-topic-maps-snapshot-1"
# Attributes under which `git archive` could write other bytes than the blob, or drop or add files. Allowed with
# their effect on an LF blob: whitespace/diff/merge (none), binary (-text -diff -merge: none), text and eol=lf (none:
# eol=lf converts only to LF). The decisive check stays empirical: every archived file hashes to its commit blob.
FORBIDDEN_ATTRIBUTES = {"export-subst", "export-ignore", "filter", "ident", "working-tree-encoding", "crlf"}
ALLOWED_EOL = {"lf", "unspecified", "unset"}
# Only the commit's own .gitattributes files count: no system file, no user file (the repo has no info/attributes).
GIT_ENV = {**os.environ, "GIT_ATTR_NOSYSTEM": "1", "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": "/dev/null"}


def git(repo, *args, data=None):
    return subprocess.run(["git", "-C", repo, "-c", "core.attributesFile=/dev/null", *args], input=data,
                          capture_output=True, check=True, env=GIT_ENV).stdout


def names(commit):
    return f"topic-maps-{commit[:8]}", f"topic-maps-{commit[:8]}-runtime.tar.gz"


def root_entries(repo, commit):
    """The root tree as Git lists it: (mode, type, id, name), in Git's order."""
    rows = []
    for line in git(repo, "ls-tree", "-z", commit).split(b"\0"):
        if line:
            meta, name = line.split(b"\t", 1)
            mode, kind, oid = meta.decode().split(" ")
            rows.append((mode, kind, oid, name.decode("utf-8")))
    return rows


def lisp_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def create(repo, commit, outdir):
    commit = git(repo, "rev-parse", "--verify", commit + "^{commit}").decode().strip()
    prefix, archive_name = names(commit)
    entries = root_entries(repo, commit)
    included = [name for (_, _, _, name) in entries if name not in EXCLUDED]
    tar = git(repo, "archive", "--format=tar", f"--prefix={prefix}/", commit, "--", *included)
    os.makedirs(outdir, exist_ok=True)
    archive = os.path.join(outdir, archive_name)
    with open(archive, "wb") as out:          # mtime 0 and no file name: the gzip bytes depend only on the tar
        with gzip.GzipFile(filename="", mode="wb", fileobj=out, mtime=0, compresslevel=9) as gz:
            gz.write(tar)
    with tempfile.TemporaryDirectory() as temp:
        with tarfile.open(archive) as t:
            t.extractall(temp, filter="tar")
        nar_hash = subprocess.run(["nix", "hash", "path", "--type", "sha256", "--sri", os.path.join(temp, prefix)],
                                  capture_output=True, check=True, text=True).stdout.strip()
    data = open(archive, "rb").read()
    commit_object = git(repo, "cat-file", "commit", commit).decode("utf-8")
    manifest = os.path.join(outdir, f"topic-maps-{commit[:8]}.manifest")
    with open(manifest, "w", encoding="utf-8", newline="\n") as out:
        out.write(f";;; Generated by scripts/topic-maps-snapshot.py from the local topic-maps repository; do not edit.\n"
                  f";;; The raw commit object and the root tree listing let the snapshot be verified without .git.\n")
        out.write(f"(:format {lisp_string(FORMAT)}\n :commit {lisp_string(commit)}\n")
        out.write(f" :commit-object {lisp_string(commit_object)}\n")
        out.write(f" :root-tree {lisp_string(git(repo, 'rev-parse', commit + '^{tree}').decode().strip())}\n")
        out.write(" :entries (" + "\n           ".join(
            f"({lisp_string(mode)} {lisp_string(kind)} {lisp_string(oid)} {lisp_string(name)})"
            for (mode, kind, oid, name) in entries) + ")\n")
        out.write(f" :excluded ({' '.join(lisp_string(e) for e in EXCLUDED)})\n")
        out.write(f" :nar-hash {lisp_string(nar_hash)}\n")
        out.write(f" :archive (:name {lisp_string(archive_name)} :prefix {lisp_string(prefix)}"
                  f" :sha256 {lisp_string(hashlib.sha256(data).hexdigest())} :octets {len(data)}))\n")
    print(json.dumps({"archive": archive, "manifest": manifest, "narHash": nar_hash,
                      "sha256": hashlib.sha256(data).hexdigest(), "octets": len(data)}, indent=1))


def read_manifest(path):
    """Only what verify compares: the generator's own fields, read back with a minimal s-expression reader."""
    text = open(path, encoding="utf-8").read()
    tokens, i = [], 0
    while i < len(text):
        c = text[i]
        if c == ";":
            i = text.index("\n", i)
        elif c in "()":
            tokens.append(c); i += 1
        elif c == '"':
            j, buf = i + 1, []
            while text[j] != '"':
                if text[j] == "\\":
                    j += 1
                buf.append(text[j]); j += 1
            tokens.append(("str", "".join(buf))); i = j + 1
        elif c.isspace():
            i += 1
        else:
            j = i
            while not text[j].isspace() and text[j] not in "()":
                j += 1
            tokens.append(("sym", text[i:j])); i = j
    def parse(k):
        if tokens[k] == "(":
            items, k = [], k + 1
            while tokens[k] != ")":
                item, k = parse(k); items.append(item)
            return items, k + 1
        kind, value = tokens[k]
        return (int(value) if kind == "sym" and value.isdigit() else value), k + 1
    form, _ = parse(0)
    return {form[n].lstrip(":"): form[n + 1] for n in range(0, len(form), 2)}


def verify(repo, commit, archive, manifest_path, evidence_path):
    started = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    checks, failures = [], []
    def check(label, ok, detail=None):
        (checks if ok else failures).append({"check": label, **({"detail": detail} if detail is not None else {})})
    commit = git(repo, "rev-parse", "--verify", commit + "^{commit}").decode().strip()
    prefix, archive_name = names(commit)
    manifest = read_manifest(manifest_path)
    data = open(archive, "rb").read()
    # The manifest is the commit's own objects.
    check("manifest-format", manifest["format"] == FORMAT)
    check("manifest-commit", manifest["commit"] == commit)
    raw = git(repo, "cat-file", "commit", commit)
    check("manifest-commit-object-is-git-object", manifest["commit-object"].encode("utf-8") == raw)
    check("commit-object-hashes-to-commit",
          hashlib.sha1(b"commit %d\0" % len(raw) + raw).hexdigest() == commit)
    tree = git(repo, "rev-parse", commit + "^{tree}").decode().strip()
    check("manifest-root-tree", manifest["root-tree"] == tree and raw.startswith(f"tree {tree}\n".encode()))
    entries = root_entries(repo, commit)
    check("manifest-root-entries", [tuple(e) for e in manifest["entries"]] == entries)
    check("manifest-archive-identity", manifest["archive"][1] == archive_name and manifest["archive"][5]
          == hashlib.sha256(data).hexdigest() and manifest["archive"][7] == len(data))
    excluded = manifest["excluded"]
    check("excluded-is-reports-only", excluded == EXCLUDED)
    for name in excluded:
        check(f"excluded-{name}-is-a-root-entry", any(e[3] == name for e in entries))
    # The commit's files, outside the excluded entries: no links, no submodules.
    listing = {}
    for line in git(repo, "ls-tree", "-r", "-z", "--full-tree", commit).split(b"\0"):
        if line:
            meta, path = line.split(b"\t", 1)
            mode, kind, oid = meta.decode().split(" ")
            path = path.decode("utf-8")
            if path.split("/", 1)[0] not in excluded:
                listing[path] = (mode, kind, oid)
    kinds = sorted({m for (m, _, _) in listing.values()})
    check("only-regular-and-executable-files", set(kinds) <= {"100644", "100755"}, kinds)
    check("no-symlinks", not any(m == "120000" for (m, _, _) in listing.values()))
    check("no-submodules", not any(k == "commit" for (_, k, _) in listing.values()))
    # .gitattributes: no attribute that changes archived bytes or membership, on any included path.
    attrs = git(repo, "check-attr", "--source", commit, "-a", "-z", "--stdin",
                data="\0".join(listing).encode("utf-8") + b"\0").split(b"\0")
    triples = [(attrs[n].decode(), attrs[n + 1].decode(), attrs[n + 2].decode()) for n in range(0, len(attrs) - 2, 3)]
    seen = sorted({(a, v) for (_, a, v) in triples})
    check("no-content-changing-attributes",
          not any(a in FORBIDDEN_ATTRIBUTES or (a == "eol" and v not in ALLOWED_EOL) for (_, a, v) in triples), seen)
    attribute_files = [p for p in listing if p == ".gitattributes" or p.endswith("/.gitattributes")]
    check("info-attributes-absent", not os.path.exists(os.path.join(
        git(repo, "rev-parse", "--path-format=absolute", "--git-common-dir").decode().strip(), "info", "attributes")))
    # The archive: exactly those files, their modes and their blob ids, under one prefix.
    members = {}
    with tarfile.open(archive) as t:
        for info in t.getmembers():
            if info.name == "pax_global_header" or info.type == tarfile.XGLTYPE:
                continue
            check_name = (info.name.rstrip("/") == prefix or info.name.startswith(prefix + "/")) and ".." not in info.name.split("/")
            if not check_name:
                failures.append({"check": "member-under-prefix", "detail": info.name}); continue
            relative = info.name[len(prefix) + 1:].rstrip("/")
            if info.isdir() and (relative == "" or info.name.startswith(prefix + "/")):
                continue
            if not info.isfile():
                failures.append({"check": "member-is-regular", "detail": info.name}); continue
            content = t.extractfile(info).read()
            mode = "100755" if info.mode & 0o111 else "100644"
            members[relative] = (mode, "blob", hashlib.sha1(b"blob %d\0" % len(content) + content).hexdigest())
    check("archive-paths-equal-commit-paths", sorted(members) == sorted(listing),
          {"missing": sorted(set(listing) - set(members))[:20], "extra": sorted(set(members) - set(listing))[:20]})
    check("archive-modes-and-blobs-equal-commit", all(members.get(p) == listing[p] for p in listing),
          [p for p in listing if members.get(p) != listing[p]][:20])
    check("no-excluded-member", not any(p.split("/", 1)[0] in excluded for p in members))
    # Git's own hashing of the extracted files, and the NAR hash Nix will pin.
    with tempfile.TemporaryDirectory() as temp:
        with tarfile.open(archive) as t:
            t.extractall(temp, filter="tar")
        root = os.path.join(temp, prefix)
        paths = sorted(listing)
        hashed = git(repo, "hash-object", "--no-filters", "--stdin-paths",
                     data="\n".join(os.path.join(root, p) for p in paths).encode() + b"\n").decode().split()
        check("git-hash-object-equals-commit-blobs", hashed == [listing[p][2] for p in paths])
        nar = subprocess.run(["nix", "hash", "path", "--type", "sha256", "--sri", root],
                             capture_output=True, check=True, text=True).stdout.strip()
        check("nar-hash-equals-manifest", nar == manifest["nar-hash"], nar)
    evidence = {"kind": "topic-maps-runtime-snapshot-verification", "startedAtUTC": started,
                "finishedAtUTC": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "repository": os.path.abspath(repo), "commit": commit, "rootTree": tree,
                "archive": {"name": archive_name, "sha256": hashlib.sha256(data).hexdigest(), "octets": len(data)},
                "narHash": manifest["nar-hash"], "excluded": excluded,
                "excludedTrees": {e[3]: e[2] for e in entries if e[3] in excluded},
                "files": len(listing), "modes": {m: sum(1 for v in listing.values() if v[0] == m) for m in kinds},
                "attributesOnIncludedPaths": seen,
                "attributeFiles": {p: git(repo, "show", f"{commit}:{p}").decode() for p in attribute_files},
                "attributedPaths": {f"{a}={v}": sum(1 for (_, x, y) in triples if (x, y) == (a, v)) for (a, v) in seen},
                "git": subprocess.run(["git", "--version"], capture_output=True, text=True, env=GIT_ENV).stdout.strip(),
                "nix": subprocess.run(["nix", "--version"], capture_output=True, text=True).stdout.strip(),
                "checks": [c["check"] for c in checks], "failures": failures, "success": not failures}
    with open(evidence_path, "w") as out:
        json.dump(evidence, out, indent=1)
    print(json.dumps({"success": not failures, "checks": len(checks), "failures": failures}, indent=1))
    return 0 if not failures else 1


if __name__ == "__main__":
    command, *args = sys.argv[1:]
    sys.exit(create(*args) if command == "create" else verify(*args))
